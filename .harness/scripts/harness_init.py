def install_opencode(dry_run: bool) -> None:
    install_common("opencode", dry_run)
    package_path = ROOT / ".opencode" / "package.json"
    try:
        package_data = json.loads(package_path.read_text(encoding="utf-8")) if package_path.exists() else {}
    except json.JSONDecodeError as error:
        raise SystemExit(f"Cannot merge invalid .opencode/package.json: {error}")
    package_data["type"] = "module"
    dependencies = package_data.setdefault("dependencies", {})
    if isinstance(dependencies, dict):
        dependencies["@opencode-ai/plugin"] = (
            opencode_plugin_version()
            or str(dependencies.get("@opencode-ai/plugin") or "1.18.4")
        )
    else:
        raise SystemExit("Cannot merge .opencode/package.json: dependencies must be an object")
    write(package_path, json.dumps(package_data, ensure_ascii=False, indent=2) + "\n", dry_run)
    write(ROOT / ".opencode" / "agents" / "harness-pm.md", opencode_pm_entry(), dry_run)
    write(ROOT / ".opencode" / "plugins" / "harness-hooks.js", OPENCODE_PLUGIN, dry_run)


def install_trae(dry_run: bool) -> None:
    install_common("trae", dry_run)
    hooks_path = ROOT / ".trae" / "hooks.json"
    if not hooks_path.exists():
        return
    try:
        data = json.loads(hooks_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return
    strip_harness_hooks(data)
    if data.get("hooks"):
        write(hooks_path, json.dumps(data, ensure_ascii=False, indent=2) + "\n", dry_run)
    else:
        remove(hooks_path, dry_run)


def main() -> int:
    parser = argparse.ArgumentParser(description="Install project-local Harness adapters.")
    parser.add_argument("--tool", choices=("all", "claude", "opencode", "trae"), default="all")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    selected = ("claude", "opencode", "trae") if args.tool == "all" else (args.tool,)
    for platform in selected:
        {"claude": install_claude, "opencode": install_opencode, "trae": install_trae}[platform](args.dry_run)
    print("Harness adapters ready: " + ", ".join(selected))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
