def python_command(platform: str | None = None) -> str:
    return "py -3" if (platform or os.name) == "nt" else "python3"


def opencode_plugin_version() -> str | None:
    executable = shutil.which("opencode")
    if not executable:
        return None
    try:
        completed = subprocess.run(
            [executable, "--version"],
            capture_output=True,
            check=False,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    output = decode_output(completed.stdout or completed.stderr)
    match = re.search(r"\b(\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?)\b", output)
    return match.group(1) if match else None


def write(path: Path, content: str, dry_run: bool) -> None:
    if dry_run:
        print(f"WRITE {path.relative_to(ROOT)}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def remove(path: Path, dry_run: bool) -> None:
    if not path.exists():
        return
    if dry_run:
        print(f"REMOVE {path.relative_to(ROOT)}")
        return
    if path.is_dir():
        shutil.rmtree(path)
    else:
        path.unlink()


